export function clientSuppliedIdempotencyKey(payload = {}) {
	return String(payload.idempotencyKey || payload.clientToken || '').trim();
}

export function isPublishJobIdempotencyUniqueViolation(error) {
	const message = String(
		error?.message
		|| error?.data?.message
		|| error?.response?.data?.message
		|| '',
	).toLowerCase();
	const code = String(error?.data?.code || error?.code || '').toLowerCase();

	if (code.includes('unique') || code.includes('constraint')) {
		return true;
	}
	if (message.includes('unique constraint') || message.includes('unique index')) {
		return true;
	}
	if (message.includes('idx_publish_jobs_owner_idempotency')) {
		return true;
	}
	if (message.includes('constraint failed') && message.includes('idempotency')) {
		return true;
	}
	return false;
}

export async function findPublishJobByOwnerIdempotencyKey(ownerId, idempotencyKey, pb) {
	return pb.collection('publish_jobs').getFirstListItem(
		pb.filter('owner = {:owner} && idempotency_key = {:key}', {
			owner: ownerId,
			key: idempotencyKey,
		}),
		{ requestKey: null },
	);
}

export async function createPublishJobIdempotent(ownerId, idempotencyKey, createBody, pb) {
	try {
		return await pb.collection('publish_jobs').create(createBody);
	} catch (error) {
		if (!isPublishJobIdempotencyUniqueViolation(error)) {
			throw error;
		}
		const existing = await findPublishJobByOwnerIdempotencyKey(ownerId, idempotencyKey, pb).catch(() => null);
		if (!existing) {
			throw error;
		}
		return existing;
	}
}

export function buildAutoGeneratedPublishIdempotencyKey(ownerId, siteId, randomHex, nowMs = Date.now()) {
	return `wp-${ownerId}-${siteId}-${nowMs}-${randomHex}`;
}
