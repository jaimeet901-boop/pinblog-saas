function httpError(status, message, extras = {}) {
	const error = new Error(message);
	error.status = status;
	Object.assign(error, extras);
	return error;
}

function fieldId(value) {
	if (value == null || value === '') return '';
	if (typeof value === 'string') return value.trim();
	if (typeof value === 'object') return String(value.id || value.value || '').trim();
	return String(value).trim();
}

export const WORDPRESS_PUBLISH_IDEMPOTENCY_WORKSPACE_REQUIRED_MESSAGE = 'Workspace is required to publish to WordPress.';

export function clientSuppliedIdempotencyKey(payload = {}) {
	return String(payload.idempotencyKey || payload.clientToken || '').trim();
}

export function requireWordpressPublishIdempotencyWorkspace(workspaceId) {
	const workspace = fieldId(workspaceId);
	if (!workspace) {
		throw httpError(422, WORDPRESS_PUBLISH_IDEMPOTENCY_WORKSPACE_REQUIRED_MESSAGE, {
			errorCode: 'WORDPRESS_PUBLISH_IDEMPOTENCY_WORKSPACE_REQUIRED',
		});
	}
	return workspace;
}

export function isPublishJobIdempotencyUniqueViolation(error) {
	const message = String(
		error?.message
		|| error?.data?.message
		|| error?.response?.data?.message
		|| '',
	).toLowerCase();
	const code = String(error?.data?.code || error?.code || '').toLowerCase();

	if (code.includes('unique') || code.includes('constraint')) {
		return true;
	}
	if (message.includes('unique constraint') || message.includes('unique index')) {
		return true;
	}
	if (message.includes('idx_publish_jobs_owner_workspace_idempotency')) {
		return true;
	}
	if (message.includes('idx_publish_jobs_owner_idempotency')) {
		return true;
	}
	if (message.includes('constraint failed') && message.includes('idempotency')) {
		return true;
	}
	return false;
}

export async function findPublishJobByOwnerWorkspaceIdempotencyKey({
	ownerId,
	workspaceId,
	idempotencyKey,
} = {}, pb) {
	const workspace = requireWordpressPublishIdempotencyWorkspace(workspaceId);
	return pb.collection('publish_jobs').getFirstListItem(
		pb.filter('owner = {:owner} && workspace = {:workspace} && idempotency_key = {:key}', {
			owner: ownerId,
			workspace,
			key: idempotencyKey,
		}),
		{ requestKey: null },
	);
}

export async function createPublishJobIdempotent({
	ownerId,
	workspaceId,
	idempotencyKey,
} = {}, createBody, pb) {
	const workspace = requireWordpressPublishIdempotencyWorkspace(workspaceId);
	try {
		return await pb.collection('publish_jobs').create(createBody);
	} catch (error) {
		if (!isPublishJobIdempotencyUniqueViolation(error)) {
			throw error;
		}
		const existing = await findPublishJobByOwnerWorkspaceIdempotencyKey({
			ownerId,
			workspaceId: workspace,
			idempotencyKey,
		}, pb).catch(() => null);
		if (!existing) {
			throw error;
		}
		return existing;
	}
}

export function wordpressPublishWaitJobIsVisible(job, { ownerId, workspaceId } = {}) {
	const workspace = fieldId(workspaceId);
	if (!workspace) return false;
	if (!job) return false;
	if (fieldId(job.owner) !== fieldId(ownerId)) return false;
	return fieldId(job.workspace || job.workspace_id) === workspace;
}

export function buildAutoGeneratedPublishIdempotencyKey(ownerId, siteId, randomHex, nowMs = Date.now()) {
	return `wp-${ownerId}-${siteId}-${nowMs}-${randomHex}`;
}
